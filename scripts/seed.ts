async function main() {
  console.log("seeding...");
  for (const i of ingredients) {
    const exists = db.select({ id: schema.ingredients.id }).from(schema.ingredients).where(eq(schema.ingredients.slug, i.slug)).get();
    if (exists) db.update(schema.ingredients).set({ ...i, published: true, updatedAt: new Date() }).where(eq(schema.ingredients.id, exists.id)).run();
    else db.insert(schema.ingredients).values({ ...i, published: true }).run();
  }
  const brandIds: Record<string, number> = {};
  for (const b of brandsData) {
    const exists = db.select({ id: schema.brands.id }).from(schema.brands).where(eq(schema.brands.slug, b.slug)).get();
    brandIds[b.slug] = exists?.id ?? db.insert(schema.brands).values(b).returning({ id: schema.brands.id }).get().id;
  }
  for (const { brand, ...p } of productsData) {
    const data = { ...p, brandId: brandIds[brand], updatedAt: new Date() };
    const exists = db.select({ id: schema.products.id }).from(schema.products).where(eq(schema.products.slug, p.slug)).get();
    const id = exists ? (db.update(schema.products).set(data).where(eq(schema.products.id, exists.id)).run(), exists.id) : db.insert(schema.products).values(data).returning({ id: schema.products.id }).get().id;
    const r = syncProductIngredients(id, p.ingredientsRaw);
    console.log(`  product ${p.slug}: matched ${r.matched}, created ${r.created}`);
  }
  for (const g of guidesData) {
    const exists = db.select({ id: schema.guides.id }).from(schema.guides).where(eq(schema.guides.slug, g.slug)).get();
    if (exists) db.update(schema.guides).set({ ...g, updatedAt: new Date() }).where(eq(schema.guides.id, exists.id)).run();
    else db.insert(schema.guides).values({ ...g, publishedAt: new Date() }).run();
  }
  console.log(`done: ${ingredients.length} ingredients, ${brandsData.length} brands, ${productsData.length} products, ${guidesData.length} guides`);
}
main();
